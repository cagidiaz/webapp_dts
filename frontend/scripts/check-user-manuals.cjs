const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const source = fs.readFileSync(path.join(__dirname, '../src/api/userManuals.ts'), 'utf8');
const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true } }).outputText;
const pdf = new Blob(['%PDF-example'], { type: 'application/pdf' });
let calls = 0, handler = async () => ({ data: pdf });
const api = { get: async (url, options) => { calls++; assert.equal(url, '/documentation/manuals/crm-clientes-contactos/pdf'); assert.equal(options.responseType, 'blob'); return handler(options); } };
const mod = { exports: {} };
new Function('require', 'module', 'exports', output)(() => api, mod, mod.exports);
const { openUserManual } = mod.exports;
const manual = { id: 'crm-clientes-contactos', version: '1.1' };
const tasks = [];
const timeout = global.setTimeout;
global.setTimeout = callback => { tasks.push(callback); return 0; };
const urls = [], revoked = [];
global.URL.createObjectURL = blob => { assert.equal(blob, pdf); const url = `blob:manual-${urls.length}`; urls.push(url); return url; };
global.URL.revokeObjectURL = url => revoked.push(url);
const popup = () => ({ opener: 'original', closed: false, document: { title: '', body: { textContent: '' } }, navigations: [], location: { replace(url) { current.navigations.push(url); } }, close() { this.closed = true; } });
let current;
async function main() {
  global.window = { open: () => null };
  await assert.rejects(openUserManual(manual, false), /ventanas emergentes/);
  assert.equal(calls, 0);
  current = popup(); global.window.open = () => current;
  await openUserManual(manual, false);
  assert.equal(current.opener, null); assert.deepEqual(current.navigations, ['blob:manual-0']);
  let link;
  global.document = { body: { appendChild() {} }, createElement: () => (link = { click() { this.clicked = true; }, remove() { this.removed = true; } }) };
  handler = async options => { assert.equal(options.params.download, '1'); return { data: pdf }; };
  await openUserManual(manual, true);
  assert.equal(link.download, 'manual-crm-clientes-contactos-v1.1.pdf'); assert.ok(link.clicked && link.removed);
  current = popup(); handler = async () => { throw new Error('403'); };
  await assert.rejects(openUserManual(manual, false), /403/); assert.equal(current.closed, true);
  current = popup(); handler = async () => ({ data: new Blob(['HTML'], { type: 'text/html' }) });
  await assert.rejects(openUserManual(manual, false), /PDF válido/); assert.equal(current.closed, true);
  for (const callback of tasks) callback();
  assert.deepEqual(revoked.sort(), urls.sort());
  console.log('6 comprobaciones correctas: visualización, descarga, bloqueo de ventanas, error de acceso, formato PDF y liberación de recursos.');
}
main().catch(error => { console.error(error.message); process.exitCode = 1; }).finally(() => { global.setTimeout = timeout; });
